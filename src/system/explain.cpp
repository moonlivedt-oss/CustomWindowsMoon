std::wstring Low(std::wstring s) {
    for (wchar_t& c : s) c = (wchar_t)towlower(c);
    return s;
}

bool Starts(const std::wstring& s, const wchar_t* prefix) { return s.rfind(prefix, 0) == 0; }

