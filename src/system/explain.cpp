std::wstring Process(const std::wstring& exe) {
    std::wstring low = Low(exe);
    size_t slash = low.find_last_of(L"\\/");
    if (slash != std::wstring::npos) low = low.substr(slash + 1);
    auto it = Known().find(low);
    if (it == Known().end() && low.size() > 4 && low.compare(low.size() - 4, 4, L".exe") != 0)
        it = Known().find(low + L".exe");
    return it == Known().end() ? L"" : it->second;
}

std::wstring Close(const std::wstring& exe) { return Join(Process(exe), kCloseHow); }

std::wstring Sleep(const std::wstring& exe) { return Join(Process(exe), kSleepHow); }

std::wstring Keep(const std::wstring& exe) { return Join(Process(exe), kKeepHow); }

