#pragma once
// Что делать с распознанным текстом (под тестами, без окон и OCR): сверить два движка, склеить перенесённые строки в
// абзацы, разложить снимок на блоки для перевода, отсеять мусор. Сам OCR - helpers/ocr.
#include <cstdint>
#include <string>
#include <vector>

namespace ocrtext {

struct Line {
    std::wstring text;
    float x = 0, y = 0, w = 0, h = 0;
};

// Связный кусок текста на снимке: реплика, пункт меню, подпись. Для перевода поверх снимка
struct Block {
    std::wstring text;
    float x = 0, y = 0, w = 0, h = 0;
    float lineH = 0;  // типичная высота строки: от неё размер шрифта перевода
    int align = 0;    // 0 - по левому краю, 1 - по центру, 2 - по правому
    bool code = false;
    int lines = 1;
};

// Доля букв в словах, похожих на настоящие, 0..1. Нечего оценивать - 1. «pa60Tana» и узор фона - низкая
double TextQuality(const std::wstring& text);
// Мусор, который в тексте для копирования не нужен: несколько «слов», почти все ненастоящие. Одно слово не выбрасываем:
// это может быть ключ или артикул, ради которого и копируют
bool IsGarbageLine(const std::wstring& text);
// Для перевода строже: на блок с мусором незачем ложиться заплаткой
bool IsGarbageBlock(const std::wstring& text);
// Переводить нечего: цифры, время, значки, одна буква
bool IsNoise(const std::wstring& text);
// Строка похожа на код или команду, а не на фразу
bool LooksLikeCode(const std::wstring& text);

// Строки основного движка (язык профиля) и английского: на одном месте берётся та, что читается лучше. Строка с точно
// русскими буквами остаётся от основного: английский движок прочёл бы её похожими латинскими. Строку, которую основной
// не увидел вовсе, добавляет английский.
std::vector<Line> MergeEngines(const std::vector<Line>& main, const std::vector<Line>& en);

// Разложить строки по блокам: строка идёт в блок, если она сразу под его последней строкой, того же размера и
// перекрывается с ним по горизонтали. Порядок - сверху вниз
std::vector<std::vector<Line>> GroupBlocks(const std::vector<Line>& lines);

// Текст для копирования. Осторожно: склеивается только перенос внутри абзаца (строка дошла почти до края блока,
// следующая начинается со строчной буквы или предыдущая кончилась запятой). Код, таблицы, списки и короткие
// подписи остаются строками, перенос по слогам чинится, мусор выбрасывается.
std::wstring CleanText(const std::vector<Line>& lines);

// Блоки для перевода: строки внутри блока склеены смелее, переводчику нужны целые предложения
std::vector<Block> MakeBlocks(const std::vector<Line>& lines);

// Во сколько раз увеличить картинку перед распознаванием: мелкий текст читается заметно точнее. Большую не трогаем
float UpscaleFactor(int w, int h);
// Оттенки серого и растяжка контраста с отсечением 2% по краям гистограммы. Пиксели 0x00RRGGBB, stride в пикселях
void GrayContrast(uint32_t* pixels, int w, int h, int stride);
// Цвет фона вокруг прямоугольника: медиана тонкой каймы. Результат 0xRRGGBB
uint32_t EdgeColor(const uint32_t* pixels, int imageW, int imageH, int stride, float x, float y, float w, float h);

}  // namespace ocrtext
