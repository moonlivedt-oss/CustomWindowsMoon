#pragma once

// Общая скорость движения и игровой режим. Все анимации берут длительность и шаг отсюда:
// «спокойно» растягивает их, «живо» ускоряет, в игровом режиме всё происходит сразу.
namespace fx {

void SetMotion(int motion);  // 0 - спокойно, 1 - обычно, 2 - живо
void SetGame(bool on);
bool Game();  // игровой режим: эффекты выключены, всё мгновенно

// длительность анимации в мс с учётом скорости (в игровом режиме 1 - сразу конец)
double Dur(double ms);
// шаг покадровой анимации (доля за кадр) с учётом скорости; в игровом режиме 1 - сразу до конца
float Step(float perFrame);

// Опрос основного окна в покое редкий (250 мс). Кто в этом такте что-то двигал (карточка, свечение, угол),
// отмечается здесь - следующий такт придёт через 20 мс.
void Active();
bool TakeActive();  // была ли отметка с прошлого раза (и сбросить)
// Что-то начало двигаться вне такта (карточка открылась по сообщению): разбудить опрос сразу, не ждать 250 мс.
void SetWaker(void (*wake)());
void Wake();

}  // namespace fx
