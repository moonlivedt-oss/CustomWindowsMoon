#pragma once
#include <windows.h>

// Один перехват мыши всей системы на всех (углы, двойной клик по столу, прозрачность окон), в своём потоке.
// Раньше у каждой части был свой WH_MOUSE_LL в основном потоке: каждое движение мыши ходило туда-обратно
// трижды, а пока основной поток занят (студия, значки из оболочки), мышь подтормаживала во всей системе.
// Обработчики вызываются в потоке перехвата: только быстрые проверки, сама работа уходит сообщением окну.
namespace llmouse {

enum Slot { DESK_CLICK, WINDOW_FX, CORNERS, kSlots };           // в таком порядке и вызываются
using Handler = bool (*)(WPARAM msg, const MSLLHOOKSTRUCT& m);  // true - событие съедено

void Set(Slot s, Handler h);  // обработчик слота: один раз, до Need
void Need(Slot s, bool on);   // слоту нужны события; перехват стоит, пока он нужен хоть одному
void Suspend(bool on);        // игровой режим: перехват снят целиком
void Shutdown();

}  // namespace llmouse
